// Escape text before inserting it into HTML.
function escapeHTML(value = "") {
    return String(value).replace(/[&<>"']/g, character => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    })[character]);
}


// Prevent unsafe or unsupported external URLs.
function safeURL(value) {
    if (!value) return "";

    try {
        const url = new URL(value, window.location.href);

        if (
            ["http:", "https:", "mailto:"].includes(url.protocol)
        ) {
            return escapeHTML(value);
        }

    } catch (error) {
        // Ignore invalid URLs.
    }

    return "";
}


// Generate tags.
function renderTags(tags = []) {
    return `
        <div class="tag-list">
            ${tags.map(tag =>
                `<span class="tag">${escapeHTML(tag)}</span>`
            ).join("")}
        </div>
    `;
}


// Generate bullet lists.
function renderList(items = []) {
    return `
        <ul>
            ${items.map(item =>
                `<li>${escapeHTML(item)}</li>`
            ).join("")}
        </ul>
    `;
}


// Generate clickable images for the lightbox.
function renderGallery(images = []) {
    if (!images.length) return "";

    return `
        <div class="project-gallery">
            ${images.map((image, index) => `
                <img
                    src="${safeURL(image)}"
                    alt="Project gallery image ${index + 1}"
                    class="zoomable"
                    loading="lazy"
                    data-caption="Project image ${index + 1}"
                >
            `).join("")}
        </div>
    `;
}


// Generate evidence button.
function evidenceButton(image, label = "View Evidence") {
    if (!image) return "";

    return `
        <button
            class="small-btn primary"
            type="button"
            data-view-image="${safeURL(image)}"
            data-caption="${escapeHTML(label)}"
        >
            <i class="fas fa-image"></i>
            ${escapeHTML(label)}
        </button>
    `;
}


// Generate an optional external link.
function externalButton(url, label, icon = "fa-external-link-alt") {
    const safe = safeURL(url);

    if (!safe || safe.startsWith("mailto:")) return "";

    return `
        <a class="small-btn" href="${safe}"
           target="_blank" rel="noopener noreferrer">
            <i class="fas ${icon}"></i>
            ${escapeHTML(label)}
        </a>
    `;
}


// Apply scroll animation to newly created content.
function observeRevealElements() {
    if (!("IntersectionObserver" in window)) {
        document.querySelectorAll(".reveal").forEach(element => {
            element.classList.add("show");
        });
        return;
    }

    document.querySelectorAll(".reveal:not(.observed)").forEach(element => {
        element.classList.add("observed");
        revealObserver.observe(element);
    });
}


