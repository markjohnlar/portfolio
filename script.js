/* =====================================================
   PART 17: IMAGE LIGHTBOX / MODAL
===================================================== */

const lightbox = document.getElementById("lightbox");
const lightboxImage = document.getElementById("lightboxImage");
const lightboxCaption = document.getElementById("lightboxCaption");

const lightboxClose = document.getElementById("lightboxClose");
const lightboxPrev = document.getElementById("lightboxPrev");
const lightboxNext = document.getElementById("lightboxNext");

let lightboxImages = [];
let currentImageIndex = 0;
let previousFocus = null;


function getGalleryImages() {

    return Array.from(document.querySelectorAll(
        ".zoomable, [data-view-image]"
    )).filter(element => {

        const source = element.dataset.viewImage || element.src;

        return Boolean(source);

    }).map(element => ({

        src: element.dataset.viewImage || element.src,

        caption:
            element.dataset.caption ||
            element.alt ||
            "Portfolio image"

    }));

}


function openLightbox(source, caption = "Portfolio image") {

    lightboxImages = getGalleryImages();

    let index = lightboxImages.findIndex(item => item.src === source);

    if (index === -1) {
        lightboxImages.push({ src: source, caption });
        index = lightboxImages.length - 1;
    }

    currentImageIndex = index;
    previousFocus = document.activeElement;

    showLightboxImage();

    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");

    document.body.style.overflow = "hidden";

    lightboxClose.focus();

}


function showLightboxImage() {

    const image = lightboxImages[currentImageIndex];

    if (!image) return;

    lightboxImage.src = image.src;
    lightboxImage.alt = image.caption;

    lightboxCaption.textContent =
        `${image.caption} (${currentImageIndex + 1}/${lightboxImages.length})`;

    const showControls = lightboxImages.length > 1;

    lightboxPrev.style.display = showControls ? "block" : "none";
    lightboxNext.style.display = showControls ? "block" : "none";

}


function closeLightbox() {

    lightbox.classList.remove("open");
    lightbox.setAttribute("aria-hidden", "true");

    document.body.style.overflow = "";

    lightboxImage.src = "";

    if (previousFocus && previousFocus.focus) {
        previousFocus.focus();
    }

}


function nextImage() {

    currentImageIndex =
        (currentImageIndex + 1) % lightboxImages.length;

    showLightboxImage();

}


function previousImage() {

    currentImageIndex =
        (currentImageIndex - 1 + lightboxImages.length) %
        lightboxImages.length;

    showLightboxImage();

}


// Event delegation: works for dynamically generated cards.
document.addEventListener("click", event => {

    const image = event.target.closest(".zoomable");

    const evidence = event.target.closest("[data-view-image]");

    if (image) {

        openLightbox(
            image.src,
            image.dataset.caption || image.alt
        );

    } else if (evidence) {

        openLightbox(
            evidence.dataset.viewImage,
            evidence.dataset.caption
        );

    }

});


lightboxClose.addEventListener("click", closeLightbox);
lightboxPrev.addEventListener("click", previousImage);
lightboxNext.addEventListener("click", nextImage);


// Close when clicking the dark background.
lightbox.addEventListener("click", event => {

    if (event.target === lightbox) {
        closeLightbox();
    }

});


// Keyboard navigation.
document.addEventListener("keydown", event => {

    if (!lightbox.classList.contains("open")) return;

    if (event.key === "Escape") {
        closeLightbox();
    }

    if (event.key === "ArrowRight") {
        nextImage();
    }

    if (event.key === "ArrowLeft") {
        previousImage();
    }

});


