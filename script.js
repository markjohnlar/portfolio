/* =====================================================
   PART 5: COURSE COMPLETIONS AND FILTER
===================================================== */

function renderCourses() {

    const grid = document.getElementById("courseGrid");
    const filters = document.getElementById("courseFilters");

    const providers = [
        "All",
        "Cisco Networking Academy",
        "Oracle Academy",
        "AWS Academy",
        "Microsoft",
        "Coursera",
        "Google",
        "Udemy",
        "Other"
    ];

    filters.innerHTML = providers.map(provider => `
        <button
            class="filter-btn ${provider === "All" ? "active" : ""}"
            data-filter="${escapeHTML(provider)}"
        >
            ${escapeHTML(provider)}
        </button>
    `).join("");

    function displayCourses(provider) {

        const filtered = portfolio.courses.filter(course =>
            provider === "All" || course.provider === provider
        );

        if (!filtered.length) {
            grid.innerHTML = `
                <p class="empty-message">
                    No courses found for this provider.
                </p>
            `;
            return;
        }

        grid.innerHTML = filtered.map(course => `

            <article class="card reveal">

                <div class="card-icon">
                    <i class="fas fa-book-open"></i>
                </div>

                <h3>${escapeHTML(course.title)}</h3>

                <p>${escapeHTML(course.provider)}</p>

                <div class="card-meta">
                    <i class="far fa-calendar-check"></i>
                    Completed: ${escapeHTML(course.date)}
                </div>

                ${evidenceButton(course.certificate, "View Evidence")}

            </article>

        `).join("");

        observeRevealElements();
    }

    filters.addEventListener("click", event => {

        const button = event.target.closest("[data-filter]");

        if (!button) return;

        filters.querySelectorAll(".filter-btn").forEach(btn => {
            btn.classList.remove("active");
        });

        button.classList.add("active");

        displayCourses(button.dataset.filter);

    });

    displayCourses("All");

}


